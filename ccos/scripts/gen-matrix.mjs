// Generates docs/role-permission-matrix.md from lib/roles.ts. Run: node scripts/gen-matrix.mjs
import fs from "node:fs";
import { PERMISSIONS, ROLES, ROLE_PERMISSIONS, ROLE_HOME } from "../lib/roles.ts";

const head = `| Role | Home department | ${PERMISSIONS.join(" | ")} |`;
const sep = `|${"---|".repeat(PERMISSIONS.length + 2)}`;
const rows = ROLES.map((r) => `| ${r} | ${ROLE_HOME[r] ?? "any (scope decides)"} | ${PERMISSIONS.map((p) => (ROLE_PERMISSIONS[r].includes(p) ? "yes" : "")).join(" | ")} |`);
const out = `# Role and permission matrix

GENERATED by \`node scripts/gen-matrix.mjs\` from \`lib/roles.ts\`. Do not edit by hand.

A permission only applies inside the scope of the grant that carries the role (org, department, property, deal, legal entity, investor).
A role with a home department can never reach records of another department, even if it is mistakenly granted org scope.

${head}
${sep}
${rows.join("\n")}

## Reading the matrix
- \`view_company_summary\`: names, stages, status, tasks, exceptions, with no money fields.
- \`view_property_financials\`: occupancy, collections, NOI, plans, milestones, renewals.
- \`view_tenant_details\`: tenant-level detail. v1 only shows a link to Rent Manager, never tenant ledgers.
- \`view_deal_financials\`: asking price, LOI price, NOI, cap rate, lender, underwriting version.
- \`view_investor_pii\`: investor identity, contact, commitments.
- \`view_executive\`: cross-department executive briefing.
- \`upload_data\`: upload the Rent Manager weekly packet (Upload data page). Owner and operations manager.
- \`request_external_write\`: reserved. No external write path exists in v1, so this grants nothing yet.
`;
fs.writeFileSync(new URL("../docs/role-permission-matrix.md", import.meta.url), out);
