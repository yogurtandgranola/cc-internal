// Generates supabase/seed_roles.sql from lib/authz.ts so SQL and TypeScript cannot drift.
// Run: node scripts/gen-roles.mjs   (a unit test fails if the committed file is stale)
import fs from "node:fs";
import { PERMISSIONS, ROLES, ROLE_PERMISSIONS } from "../lib/roles.ts";

const HOME = { ops_manager: "operations", ops_staff: "operations", acquisitions_manager: "acquisitions", acquisitions_staff: "acquisitions", ir_manager: "ir", ir_staff: "ir" };
export function build() {
  const q = (s) => `'${s}'`;
  const lines = ["-- GENERATED by scripts/gen-roles.mjs from lib/authz.ts. Do not edit.", ""];
  lines.push(`insert into public.roles (id) values ${ROLES.map((r) => `(${q(r)})`).join(", ")} on conflict do nothing;`);
  lines.push(`insert into public.permissions (id) values ${PERMISSIONS.map((p) => `(${q(p)})`).join(", ")} on conflict do nothing;`);
  const rp = ROLES.flatMap((r) => ROLE_PERMISSIONS[r].map((p) => `(${q(r)}, ${q(p)})`));
  lines.push(`insert into public.role_permissions (role, permission) values\n  ${rp.join(",\n  ")}\non conflict do nothing;`);
  lines.push(`insert into public.role_home_department (role, department) values ${Object.entries(HOME).map(([r, d]) => `(${q(r)}, ${q(d)})`).join(", ")} on conflict do nothing;`);
  return lines.join("\n") + "\n";
}
if (process.argv[1]?.endsWith("gen-roles.mjs")) fs.writeFileSync(new URL("../supabase/seed_roles.sql", import.meta.url), build());
